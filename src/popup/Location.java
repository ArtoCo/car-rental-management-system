    private LocalTime parsePickupTime(String timeText) {
        String cleanTime = timeText == null ? "" : timeText.trim().toUpperCase(Locale.ENGLISH);
        DateTimeFormatter[] formats = new DateTimeFormatter[]{
            DateTimeFormatter.ofPattern("h:mm a", Locale.ENGLISH),
            DateTimeFormatter.ofPattern("hh:mm a", Locale.ENGLISH),
            DateTimeFormatter.ofPattern("H:mm", Locale.ENGLISH),
            DateTimeFormatter.ofPattern("HH:mm", Locale.ENGLISH)
        };

        for (DateTimeFormatter format : formats) {
            try {
                return LocalTime.parse(cleanTime, format);
            } catch (DateTimeParseException ignored) {
            }
        }
        throw new IllegalArgumentException("Invalid pickup time format.");
    }
    
