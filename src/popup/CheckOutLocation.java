    private void rSMaterialButtonRectangle1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rSMaterialButtonRectangle1ActionPerformed
            // Inputs
    String dateStr  = jFormattedTextField2.getText().trim(); // dd/MM/yyyy
    String time     = jFormattedTextField3.getText().trim();
    String location = txt.getText().trim();

    if (!routeMap.matchesDraftOrSavedSelection(location)) {
        JOptionPane.showMessageDialog(this, "Please select a return location on the map.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (dateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a check-out date.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (time.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a return time.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        // ✅ Parse dd/MM/yyyy once
        DateTimeFormatter inputFmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        LocalDate checkOutLocalDate = LocalDate.parse(dateStr, inputFmt);
        LocalTime checkOutLocalTime = parseReturnTime(time);

        String pickupDateText = AppSession2.getCheckInDateFormatted();
        String pickupTimeText = AppSession2.getCheckInTime();
        if (pickupDateText == null || pickupDateText.trim().isEmpty()
                || pickupTimeText == null || pickupTimeText.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please save pickup date and time first.",
                    "Pickup Required",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        LocalDate pickupDate = LocalDate.parse(
                pickupDateText.trim(),
                DateTimeFormatter.ofPattern("MMMM dd yyyy", Locale.ENGLISH));
        LocalTime pickupTime = parseReturnTime(pickupTimeText);

        if (checkOutLocalDate.isBefore(pickupDate)) {
            JOptionPane.showMessageDialog(this,
                    "Return date cannot be before pickup date.",
                    "Invalid Return Date",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (checkOutLocalDate.equals(pickupDate)
                && !checkOutLocalTime.isAfter(pickupTime)) {
            JOptionPane.showMessageDialog(this,
                    "Return time must be after pickup time.",
                    "Invalid Return Time",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Confirm this return location?\n" + location,
                "Confirm Return Location",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        // ✅ SQL Date for DB update
        java.sql.Date sqlCheckOutDate = java.sql.Date.valueOf(checkOutLocalDate);

        // ✅ Receipt format: "June 28 2025"
        String receiptOutDate = checkOutLocalDate.format(DateTimeFormatter.ofPattern("MMMM dd yyyy"));

        // ✅ Get phone from AppSession2 -> CustomerInfo (NOT AppSession)
        CustomerInfo info = AppSession2.getCustomerInfo();
        if (info == null) {
            JOptionPane.showMessageDialog(this, "Customer session is missing. Save customer first.", "Session Missing", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String phoneNumber = info.getPhoneNumber();
        if (phoneNumber == null || phoneNumber.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Phone number missing in session.", "Session Missing", JOptionPane.ERROR_MESSAGE);
            return;
        }
        Integer customerId = AppSession2.getCustomerId();
        if (customerId == null) {
            customerId = AppSession.getSelectedCustomerIdForBooking();
        }
        if (customerId == null) {
            customerId = AppSession.getCustomerId();
        }
        if (customerId == null) {
            JOptionPane.showMessageDialog(this, "Customer ID missing in session.", "Session Missing", JOptionPane.ERROR_MESSAGE);
            return;
        }
        AppSession2.setCustomerId(customerId);

        // ✅ Update DB
        ServiceCustomer service = new ServiceCustomer();
        service.updateCheckoutInfoByVerifiedCustomer(
                customerId,
                info.getFirstName(),
                info.getLastName(),
                phoneNumber,
                sqlCheckOutDate,
                time,
                location
        );
        routeMap.commitSavedSelection();

        // ✅ Green dot logic (your existing feature)
        CheckOutDateStore.addCheckOutDate(checkOutLocalDate);

        // ✅ Update receipt OUT date (FULL_RECEIPT uses info.getFormattedOutDate())
        info.setFormattedOutDate(receiptOutDate);

        // Save back (same object reference, but safe)
        AppSession2.setCustomerInfo(info);

        // ✅ optional: also store checkout info in AppSession2
        AppSession2.setCheckOutDateFormatted(receiptOutDate);
        AppSession2.setCheckOutTime(time);
        AppSession2.setCheckOutLocation(location);

        JOptionPane.showMessageDialog(this, "Return information saved successfully!");

    } catch (DateTimeParseException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Invalid check-out date format! Please use dd/MM/yyyy.", "Date Error", JOptionPane.ERROR_MESSAGE);

    } catch (IllegalArgumentException ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "Time Error", JOptionPane.ERROR_MESSAGE);

    } catch (Exception ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
    }
    
    }//GEN-LAST:event_rSMaterialButtonRectangle1ActionPerformed

