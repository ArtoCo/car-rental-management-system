    private void rSMaterialButtonRectangle1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rSMaterialButtonRectangle1ActionPerformed
        // TODO add your handling code here:


    // Inputs
    String dateStr  = jFormattedTextField1.getText().trim();   // dd/MM/yyyy
    String time     = jFormattedTextField2.getText().trim();
    String location = txt.getText().trim();                   // your location textfield

    if (!pickupMap.matchesDraftOrSavedSelection(location)) {
        JOptionPane.showMessageDialog(this, "Please select a pickup location on the map.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (dateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a Pickup date.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (time.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a Pickup time.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        // ✅ Parse dd/MM/yyyy once
        DateTimeFormatter inputFmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        LocalDate checkInLocalDate = LocalDate.parse(dateStr, inputFmt);
        LocalTime checkInLocalTime = parsePickupTime(time);
        LocalDate today = LocalDate.now();

        if (checkInLocalDate.isBefore(today)) {
            JOptionPane.showMessageDialog(this, "Pickup date cannot be in the past.", "Invalid Pickup Date", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (checkInLocalDate.equals(today)) {
            LocalTime now = LocalTime.now().withSecond(0).withNano(0);
            if (checkInLocalTime.isBefore(now)) {
                JOptionPane.showMessageDialog(this, "Pickup time cannot be in the past.", "Invalid Pickup Time", JOptionPane.WARNING_MESSAGE);
                return;
            }
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Confirm this pickup location?\n" + location,
                "Confirm Pickup Location",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        // ✅ SQL Date for DB update
        java.sql.Date sqlInDate = java.sql.Date.valueOf(checkInLocalDate);

        // ✅ Receipt format: "June 28 2025"
        String receiptDate = checkInLocalDate.format(DateTimeFormatter.ofPattern("MMMM dd yyyy"));

        // ✅ Get phone from AppSession2 -> CustomerInfo (NOT AppSession)
        CustomerInfo info = AppSession2.getCustomerInfo();
        if (info == null) {
            JOptionPane.showMessageDialog(this, "Customer session is missing. Save customer first.", "Session Missing", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String phoneNumber = info.getPhoneNumber();
        if (phoneNumber == null || phoneNumber.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Phone number missing in session.", "Session Missing", JOptionPane.ERROR_MESSAGE);
            return;
        }
        Integer customerId = AppSession2.getCustomerId();
        if (customerId == null) {
            customerId = AppSession.getSelectedCustomerIdForBooking();
        }
        if (customerId == null) {
            customerId = AppSession.getCustomerId();
        }
        if (customerId == null) {
            JOptionPane.showMessageDialog(this, "Customer ID missing in session.", "Session Missing", JOptionPane.ERROR_MESSAGE);
            return;
        }
        AppSession2.setCustomerId(customerId);

        // ✅ Update DB
        ServiceCustomer service = new ServiceCustomer();
        service.updateCheckinInfoByVerifiedCustomer(
                customerId,
                info.getFirstName(),
                info.getLastName(),
                phoneNumber,
                sqlInDate,
                time,
                location
        );
        pickupMap.commitSavedSelection();

        // ✅ Green dot logic (your existing feature)
        CheckInDateStore.addCheckInDate(checkInLocalDate);

        // ✅ Update receipt date (FULL_RECEIPT uses info.getFormattedDate())
        info.setFormattedDate(receiptDate);

        // Save back (same object reference, but safe)
        AppSession2.setCustomerInfo(info);

        // ✅ optional: also store location/time in AppSession2
        AppSession2.setCheckInDateFormatted(receiptDate);
        AppSession2.setCheckInTime(time);
        AppSession2.setCheckInLocation(location);

        JOptionPane.showMessageDialog(this, "Pickup information saved successfully!");

    } catch (DateTimeParseException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Invalid date format! Please use dd/MM/yyyy.", "Date Error", JOptionPane.ERROR_MESSAGE);

    } catch (IllegalArgumentException ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "Time Error", JOptionPane.ERROR_MESSAGE);

    } catch (Exception ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_rSMaterialButtonRectangle1ActionPerformed

