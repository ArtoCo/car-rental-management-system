public void setEditData(ModelSched data) {
    editingId = data.getid();
    jTextField1.setText(data.getfirstname());
    jTextField2.setText(data.getlastname());
    jTextField3.setText(data.getphoneNO());
    jFormatted.setText(data.getcheckins());
    jTextField5.setText(data.getPayments());
    jTextField6.setText(data.getTotal_payments());
}

public ModelSched getData() {
    try {
        // ✅ 1. Parse the date from jFormatted
        DateFormat df = new SimpleDateFormat("dd/MM/yyyy");
        Date parsedDate = df.parse(jFormatted.getText().trim());

        // ✅ 2. Get current time in 12-hour format
        LocalTime now = LocalTime.now();
        DateTimeFormatter timeFormatter = DateTimeFormatter.ofPattern("h:mm a");
        String currentTime = now.format(timeFormatter);

        // ✅ 3. Format the date as "MMMM dd, yyyy"
        DateFormat fullDateFormat = new SimpleDateFormat("MMMM dd, yyyy");
        String formattedDate = fullDateFormat.format(parsedDate);

        // ✅ 4. Combine date + time
        String fullCheckin = formattedDate + " - " + currentTime;

        return new ModelSched(
            editingId,
            jTextField1.getText().trim(),
            jTextField2.getText().trim(),
            jTextField3.getText().trim(),
            "", // car name not edited here
            fullCheckin,
            jTextField5.getText().trim(),   // Payments
            jTextField6.getText().trim()    // Total payments
        );

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Invalid date format!");
        return null;
    }
}




