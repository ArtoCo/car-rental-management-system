    if (result == JFileChooser.APPROVE_OPTION) {
        File selectedFile = fileChooser.getSelectedFile();
        selectedImagePath = selectedFile.getAbsolutePath();  // ⬅️ store the image path

        // Resize and show the image in jLabel32
        ImageIcon originalIcon = new ImageIcon(selectedImagePath);
        Image image = originalIcon.getImage().getScaledInstance(jLabel32.getWidth(), jLabel32.getHeight(), Image.SCALE_SMOOTH);
        jLabel32.setIcon(new ImageIcon(image));
    }
